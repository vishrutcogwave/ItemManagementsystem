-- =====================================================================
-- Silent thermal printing: printer configurations, paired bridge
-- devices and print job history. Everything stays inside the shared
-- PostgreSQL database and is isolated by store_id / branch_id.
-- =====================================================================

CREATE TABLE printer_configs (
    id                BIGSERIAL PRIMARY KEY,
    store_id          BIGINT       NOT NULL REFERENCES stores(id),
    branch_id         BIGINT       NOT NULL,
    printer_name      VARCHAR(100) NOT NULL,
    ip_address        VARCHAR(120) NOT NULL,
    port              INTEGER      NOT NULL DEFAULT 9100
        CHECK (port BETWEEN 1 AND 65535),
    paper_width       VARCHAR(8)   NOT NULL DEFAULT 'MM80'
        CHECK (paper_width IN ('MM58', 'MM80')),
    purpose           VARCHAR(16)  NOT NULL DEFAULT 'RECEIPT'
        CHECK (purpose IN ('RECEIPT', 'PURCHASE', 'REPORT', 'ALL')),
    status            VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    last_test_at      TIMESTAMPTZ,
    last_test_message VARCHAR(255),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_printer_config_name UNIQUE (store_id, branch_id, printer_name),
    CONSTRAINT fk_printer_branch FOREIGN KEY (branch_id, store_id)
        REFERENCES branches(id, store_id)
);

CREATE INDEX ix_printer_configs_store ON printer_configs (store_id, branch_id, status);

-- One-time codes generated by the store owner and typed into a print
-- bridge. Only the SHA-256 hash is stored; the plain code is returned
-- once and expires after ten minutes.
CREATE TABLE print_pairing_codes (
    id          BIGSERIAL PRIMARY KEY,
    store_id    BIGINT       NOT NULL REFERENCES stores(id),
    branch_id   BIGINT       NOT NULL,
    code_hash   VARCHAR(64)  NOT NULL UNIQUE,
    created_by  BIGINT       REFERENCES users(id),
    expires_at  TIMESTAMPTZ  NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_pairing_branch FOREIGN KEY (branch_id, store_id)
        REFERENCES branches(id, store_id)
);

CREATE INDEX ix_print_pairing_codes_store ON print_pairing_codes (store_id, expires_at);

-- A paired bridge receives a long-lived opaque token. The website never
-- sees this token; the bridge uses it only to pull printer configs.
CREATE TABLE print_devices (
    id                  BIGSERIAL PRIMARY KEY,
    store_id            BIGINT       NOT NULL REFERENCES stores(id),
    branch_id           BIGINT       NOT NULL,
    device_name         VARCHAR(100) NOT NULL,
    platform            VARCHAR(16)  NOT NULL CHECK (platform IN ('ANDROID', 'WINDOWS')),
    token_hash          VARCHAR(64)  NOT NULL UNIQUE,
    status              VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'REVOKED')),
    paired_by           BIGINT       REFERENCES users(id),
    paired_by_username  VARCHAR(80),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_seen_at        TIMESTAMPTZ,
    CONSTRAINT fk_device_branch FOREIGN KEY (branch_id, store_id)
        REFERENCES branches(id, store_id)
);

CREATE INDEX ix_print_devices_store ON print_devices (store_id, branch_id, status);

-- Every automatic print is keyed so a receipt can never be sent twice
-- by an accidental double click or a page refresh. Manual reprints are
-- recorded as separate MANUAL rows.
CREATE TABLE print_jobs (
    id                BIGSERIAL PRIMARY KEY,
    store_id          BIGINT       NOT NULL REFERENCES stores(id),
    branch_id         BIGINT       NOT NULL,
    job_key           VARCHAR(150) NOT NULL,
    document_type     VARCHAR(20)  NOT NULL
        CHECK (document_type IN ('SALE_RECEIPT', 'PURCHASE', 'TEST')),
    document_id       BIGINT,
    document_number   VARCHAR(60),
    printer_config_id BIGINT       REFERENCES printer_configs(id) ON DELETE SET NULL,
    printer_name      VARCHAR(100),
    channel           VARCHAR(16)  NOT NULL CHECK (channel IN ('WINDOWS', 'ANDROID')),
    trigger_type      VARCHAR(10)  NOT NULL CHECK (trigger_type IN ('AUTO', 'MANUAL')),
    status            VARCHAR(16)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PRINTED', 'FAILED')),
    attempts          INTEGER      NOT NULL DEFAULT 0,
    error_message     VARCHAR(500),
    created_by        BIGINT       REFERENCES users(id),
    created_by_username VARCHAR(80),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    printed_at        TIMESTAMPTZ,
    CONSTRAINT uq_print_job_store_key UNIQUE (store_id, job_key),
    CONSTRAINT fk_print_job_branch FOREIGN KEY (branch_id, store_id)
        REFERENCES branches(id, store_id)
);

CREATE INDEX ix_print_jobs_store ON print_jobs (store_id, created_at DESC);
CREATE INDEX ix_print_jobs_branch ON print_jobs (store_id, branch_id, created_at DESC);

-- Printing permissions for existing stores. Store owners/admins manage
-- printer configuration; managers can view it.
INSERT INTO permissions (code, name, description) VALUES
('PRINTER_VIEW', 'View printers', 'View printer configuration and print history'),
('PRINTER_MANAGE', 'Manage printers', 'Add or remove printers and pair print bridges');

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'PRINTER_VIEW'
WHERE r.store_id IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'PRINTER_MANAGE'
WHERE r.store_id IS NOT NULL AND r.code IN ('STORE_OWNER', 'STORE_ADMIN')
ON CONFLICT DO NOTHING;
